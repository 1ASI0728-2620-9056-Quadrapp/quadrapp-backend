-- Initial schema of the Parking Configuration bounded context.
-- Flyway runs this file inside the module schema; the schema itself is created by Flyway.

CREATE TABLE configuration.accesses (
    flow_counting_enabled boolean NOT NULL,
    created_at timestamp with time zone NOT NULL,
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    lot_id bigint NOT NULL,
    updated_at timestamp with time zone NOT NULL,
    type character varying(15) NOT NULL,
    name character varying(60) NOT NULL,
    CONSTRAINT accesses_type_check CHECK (((type)::text = ANY ((ARRAY['ENTRY'::character varying, 'EXIT'::character varying, 'BIDIRECTIONAL'::character varying])::text[])))
);

CREATE TABLE configuration.calendar_events (
    impact character varying(6) NOT NULL,
    cancelled_at timestamp with time zone,
    created_at timestamp with time zone NOT NULL,
    created_by bigint,
    ends_at timestamp with time zone NOT NULL,
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    institution_id bigint NOT NULL,
    lot_id bigint,
    starts_at timestamp with time zone NOT NULL,
    updated_at timestamp with time zone NOT NULL,
    zone_id bigint,
    type character varying(15) NOT NULL,
    name character varying(120) NOT NULL,
    CONSTRAINT calendar_events_impact_check CHECK (((impact)::text = ANY ((ARRAY['LOW'::character varying, 'MEDIUM'::character varying, 'HIGH'::character varying])::text[]))),
    CONSTRAINT calendar_events_type_check CHECK (((type)::text = ANY ((ARRAY['CLASSES'::character varying, 'EXAMS'::character varying, 'RECESS'::character varying, 'CAMPUS_EVENT'::character varying])::text[])))
);

CREATE TABLE configuration.levels (
    sort_order smallint NOT NULL,
    created_at timestamp with time zone NOT NULL,
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    updated_at timestamp with time zone NOT NULL,
    zone_id bigint NOT NULL,
    name character varying(40) NOT NULL
);

CREATE TABLE configuration.parking_lots (
    accuracy_margin_pct smallint NOT NULL,
    active boolean NOT NULL,
    closes_at time(0) without time zone,
    flow_window_minutes smallint NOT NULL,
    freed_debounce_s smallint NOT NULL,
    latitude numeric(9,6),
    layout_version integer NOT NULL,
    longitude numeric(9,6),
    low_battery_threshold_pct smallint NOT NULL,
    occupied_debounce_s smallint NOT NULL,
    opens_at time(0) without time zone,
    saturation_threshold_pct smallint NOT NULL,
    stale_after_seconds integer NOT NULL,
    created_at timestamp with time zone NOT NULL,
    created_by bigint,
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    institution_id bigint NOT NULL,
    layout_published_at timestamp with time zone,
    updated_at timestamp with time zone NOT NULL,
    name character varying(120) NOT NULL,
    address character varying(255)
);

CREATE TABLE configuration.spaces (
    active boolean NOT NULL,
    pos_x numeric(7,2),
    pos_y numeric(7,2),
    created_at timestamp with time zone NOT NULL,
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    last_event_at timestamp with time zone,
    level_id bigint NOT NULL,
    status_since timestamp with time zone NOT NULL,
    updated_at timestamp with time zone NOT NULL,
    status character varying(10) NOT NULL,
    type character varying(10) NOT NULL,
    label character varying(20) NOT NULL,
    unknown_reason character varying(25),
    CONSTRAINT spaces_status_check CHECK (((status)::text = ANY ((ARRAY['FREE'::character varying, 'OCCUPIED'::character varying, 'UNKNOWN'::character varying])::text[]))),
    CONSTRAINT spaces_type_check CHECK (((type)::text = ANY ((ARRAY['STANDARD'::character varying, 'ACCESSIBLE'::character varying])::text[]))),
    CONSTRAINT spaces_unknown_reason_check CHECK (((unknown_reason)::text = ANY ((ARRAY['NO_HEARTBEAT'::character varying, 'LOW_BATTERY'::character varying, 'NO_SENSOR'::character varying])::text[])))
);

CREATE TABLE configuration.zones (
    sort_order smallint NOT NULL,
    created_at timestamp with time zone NOT NULL,
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    lot_id bigint NOT NULL,
    updated_at timestamp with time zone NOT NULL,
    name character varying(60) NOT NULL,
    description character varying(80)
);

