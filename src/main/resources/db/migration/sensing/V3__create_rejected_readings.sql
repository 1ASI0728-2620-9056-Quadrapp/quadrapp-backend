-- Gateway messages that were acknowledged without being processed: malformed messages and
-- messages whose processing still failed after every retry. The payload is kept as received.
CREATE TABLE sensing.rejected_readings (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    topic text NOT NULL,
    payload text NOT NULL,
    reason text NOT NULL,
    received_at timestamp with time zone NOT NULL
);

CREATE INDEX ix_rejected_readings_received_at ON sensing.rejected_readings (received_at);
