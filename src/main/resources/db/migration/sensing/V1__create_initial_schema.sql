-- Initial schema of the Parking Sensing bounded context.
-- Flyway runs this file inside the module schema; the schema itself is created by Flyway.

CREATE TABLE sensing.device_incidents (
    detected_at timestamp with time zone NOT NULL,
    device_id bigint,
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    lot_id bigint NOT NULL,
    reported_by bigint,
    resolved_at timestamp with time zone,
    resolved_by bigint,
    category character varying(20),
    type character varying(25) NOT NULL,
    hardware_id character varying(80),
    detail text,
    CONSTRAINT device_incidents_category_check CHECK (((category)::text = ANY ((ARRAY['NO_COMMUNICATION'::character varying, 'WRONG_DATA'::character varying, 'LOW_BATTERY'::character varying, 'OTHER'::character varying])::text[]))),
    CONSTRAINT device_incidents_type_check CHECK (((type)::text = ANY ((ARRAY['NO_HEARTBEAT'::character varying, 'LOW_BATTERY'::character varying, 'UNREGISTERED_DEVICE'::character varying, 'UNMAPPED_SENSOR'::character varying, 'INVALID_MESSAGE'::character varying, 'USER_REPORT'::character varying])::text[])))
);

CREATE TABLE sensing.devices (
    battery_pct smallint,
    directional boolean,
    expected_report_interval_s integer NOT NULL,
    access_id bigint,
    created_at timestamp with time zone NOT NULL,
    decommissioned_at timestamp with time zone,
    gateway_id bigint,
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    last_seen_at timestamp with time zone,
    lot_id bigint NOT NULL,
    registered_by bigint,
    replaced_by bigint,
    space_id bigint,
    updated_at timestamp with time zone NOT NULL,
    status character varying(15) NOT NULL,
    type character varying(20) NOT NULL,
    firmware_version character varying(30),
    hardware_id character varying(80) NOT NULL,
    api_key_hash character varying(255),
    CONSTRAINT devices_status_check CHECK (((status)::text = ANY ((ARRAY['OPERATIONAL'::character varying, 'UNREACHABLE'::character varying, 'LOW_BATTERY'::character varying, 'DECOMMISSIONED'::character varying])::text[]))),
    CONSTRAINT devices_type_check CHECK (((type)::text = ANY ((ARRAY['SPACE_SENSOR'::character varying, 'PASS_SENSOR'::character varying, 'GATEWAY'::character varying])::text[])))
);

ALTER TABLE sensing.device_incidents
    ADD CONSTRAINT device_incidents_pkey PRIMARY KEY (id);

ALTER TABLE sensing.devices
    ADD CONSTRAINT devices_pkey PRIMARY KEY (id);

ALTER TABLE sensing.devices
    ADD CONSTRAINT uk_devices_hardware_id UNIQUE (hardware_id);
