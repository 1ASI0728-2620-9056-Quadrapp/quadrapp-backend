-- Initial schema of the Prediction bounded context.
-- Flyway runs this file inside the module schema; the schema itself is created by Flyway.
-- lot_id identifies a parking lot of the configuration schema: it carries no foreign key,
-- because no constraint may cross module schemas (CON-02).

CREATE TABLE prediction.forecasts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lot_id bigint NOT NULL,
    horizon_min smallint NOT NULL,
    generated_at timestamptz NOT NULL DEFAULT now(),
    target_at timestamptz NOT NULL,
    expected_occupancy_pct numeric(5,2) NOT NULL,
    confidence numeric(4,3) NOT NULL,
    confidence_level varchar(6) NOT NULL,
    method varchar(15) NOT NULL,
    model_version varchar(40) NOT NULL,
    saturation_expected_at timestamptz,
    observed_occupancy_pct numeric(5,2),
    abs_error numeric(5,2),
    CONSTRAINT uk_forecasts_lot_horizon_generated UNIQUE (lot_id, horizon_min, generated_at),
    CONSTRAINT ck_forecasts_horizon CHECK (horizon_min IN (15, 30, 45, 60)),
    CONSTRAINT ck_forecasts_expected_occupancy CHECK (expected_occupancy_pct BETWEEN 0 AND 100),
    CONSTRAINT ck_forecasts_confidence CHECK (confidence BETWEEN 0 AND 1),
    CONSTRAINT ck_forecasts_confidence_level CHECK (confidence_level IN ('HIGH', 'MEDIUM', 'LOW')),
    CONSTRAINT ck_forecasts_method CHECK (method IN ('PRIMARY_MODEL', 'FALLBACK')),
    CONSTRAINT ck_forecasts_observed_occupancy CHECK (observed_occupancy_pct BETWEEN 0 AND 100),
    CONSTRAINT ck_forecasts_fallback_confidence CHECK (method <> 'FALLBACK' OR confidence_level = 'LOW')
);
