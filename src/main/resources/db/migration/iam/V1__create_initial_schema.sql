-- Initial schema of the IAM bounded context.
-- Flyway runs this file inside the module schema; the schema itself is created by Flyway.

CREATE TABLE iam.institution_domains (
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    institution_id bigint NOT NULL,
    verified_at timestamp with time zone,
    verified_by bigint,
    domain character varying(120) NOT NULL,
    CONSTRAINT ck_institution_domains_lowercase CHECK (((domain)::text = lower((domain)::text)))
);

CREATE TABLE iam.institutions (
    active boolean DEFAULT true NOT NULL,
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    updated_at timestamp with time zone DEFAULT now() NOT NULL,
    name character varying(150) NOT NULL
);

CREATE TABLE iam.refresh_tokens (
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    expires_at timestamp with time zone NOT NULL,
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    revoked_at timestamp with time zone,
    user_id bigint NOT NULL,
    token_hash character varying(255) NOT NULL
);

CREATE TABLE iam.users (
    event_alerts boolean DEFAULT false NOT NULL,
    low_arrival_alerts boolean DEFAULT true NOT NULL,
    push_enabled boolean DEFAULT true NOT NULL,
    saturation_alerts boolean DEFAULT true NOT NULL,
    stale_data_alerts boolean DEFAULT true NOT NULL,
    locale character varying(6) DEFAULT 'es-419'::character varying NOT NULL,
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    institution_id bigint,
    invitation_expires_at timestamp with time zone,
    invited_by bigint,
    last_login_at timestamp with time zone,
    updated_at timestamp with time zone DEFAULT now() NOT NULL,
    verified_at timestamp with time zone,
    status character varying(10) DEFAULT 'ACTIVE'::character varying NOT NULL,
    role character varying(15) NOT NULL,
    full_name character varying(120),
    email character varying(254) NOT NULL,
    invitation_token_hash character varying(255),
    CONSTRAINT ck_users_invitation CHECK ((((status)::text <> 'INVITED'::text) OR ((invitation_token_hash IS NOT NULL) AND (invitation_expires_at IS NOT NULL)))),
    CONSTRAINT ck_users_locale CHECK (((locale)::text = ANY ((ARRAY['es-419'::character varying, 'en-US'::character varying])::text[]))),
    CONSTRAINT ck_users_lowercase_email CHECK (((email)::text = lower((email)::text))),
    CONSTRAINT ck_users_platform_admin CHECK ((((role)::text = 'PLATFORM_ADMIN'::text) = (institution_id IS NULL))),
    CONSTRAINT ck_users_role CHECK (((role)::text = ANY ((ARRAY['DRIVER'::character varying, 'OPERATOR'::character varying, 'ADMIN'::character varying, 'PLATFORM_ADMIN'::character varying])::text[]))),
    CONSTRAINT ck_users_status CHECK (((status)::text = ANY ((ARRAY['INVITED'::character varying, 'ACTIVE'::character varying, 'DISABLED'::character varying])::text[])))
);

