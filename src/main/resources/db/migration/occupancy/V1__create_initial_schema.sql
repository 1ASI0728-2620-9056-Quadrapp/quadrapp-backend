-- Initial schema of the Occupancy bounded context.
-- Flyway runs this file inside the module schema; the schema itself is created by Flyway.
-- device_id, space_id, access_id and zone_id identify records of other modules: they carry no
-- foreign key, because no constraint may cross module schemas (CON-02).

CREATE TABLE occupancy.sensor_events (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id varchar(100) NOT NULL,
    device_id bigint NOT NULL,
    space_id bigint,
    access_id bigint,
    event_type varchar(10) NOT NULL,
    occurred_at timestamptz NOT NULL,
    received_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT sensor_events_event_id_key UNIQUE (event_id),
    CONSTRAINT ck_sensor_events_type CHECK (event_type IN ('OCCUPIED', 'FREED', 'ENTRY', 'EXIT')),
    CONSTRAINT ck_sensor_events_kind CHECK (
        (event_type IN ('OCCUPIED', 'FREED') AND space_id IS NOT NULL AND access_id IS NULL)
        OR (event_type IN ('ENTRY', 'EXIT') AND access_id IS NOT NULL AND space_id IS NULL)
    )
);

CREATE TABLE occupancy.occupancy_snapshots (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    zone_id bigint NOT NULL,
    taken_at timestamptz NOT NULL,
    total_spaces smallint NOT NULL,
    free_count smallint NOT NULL,
    occupied_count smallint NOT NULL,
    unknown_count smallint NOT NULL,
    CONSTRAINT uk_occupancy_snapshots_zone_taken UNIQUE (zone_id, taken_at),
    CONSTRAINT ck_occupancy_snapshots_total CHECK (free_count + occupied_count + unknown_count = total_spaces)
);
